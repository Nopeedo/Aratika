/**
 * The 71 electorates contested at the 2026 General Election.
 *
 * WHY THIS FILE EXISTS SEPARATELY FROM electorates-data.ts. Those are two
 * different things, and conflating them put 43 people who are not standing on
 * the live site while 138 real candidates were missing.
 *   - electorates-data.ts  = the 72 seats of the 2023 election, who holds each
 *     one now, and the Stats NZ "General & Māori Electorates 2020" geometry the
 *     map draws. It is about the CURRENT Parliament and is still correct for that.
 *   - this file            = what people are actually voting for on 7 Nov 2026.
 *
 * The Representation Commission released the final 2026 boundaries and names on
 * 8 August 2025. The lower North Island fell below population quota, so the
 * country went from 72 seats to 71: 64 general and 7 Māori.
 *
 * GENERATED by scripts/gen-electorates-2026.mjs from the Electoral Commission's
 * official candidate list (scripts/data/electorate-candidates-2026.csv,
 * published 9 October 2026, nominations closed). Do not hand-edit: every seat
 * here is one the Commission actually accepted nominations for, which is why a
 * typo cannot creep in. The generator asserts the 71/64/7 split and throws
 * if the CSV stops agreeing with it.
 *
 * `candidates` is the official count per seat, kept as a check: if the ingest
 * produces a different number for a seat, one of the two is wrong.
 */

export interface Electorate2026 {
  name: string
  slug: string
  type: 'general' | 'maori'
  /** Created in the 2025 boundary review — so it has NO sitting MP, and the
   *  battleground page must not render a defender for it. */
  newIn2026?: boolean
  /** Official candidate count from the Electoral Commission's list. */
  candidates: number
}

