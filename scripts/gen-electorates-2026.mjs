/**
 * gen-electorates-2026.mjs — emit src/constants/electorates-2026.ts from the
 * Electoral Commission's official candidate list.
 *
 * The 2026 seats are DERIVED, never transcribed. Every name here is a seat the
 * Commission actually accepted nominations for, so the file cannot drift from
 * the authority by a typo. Re-run after replacing the vendored CSV.
 *
 * Run: node scripts/gen-electorates-2026.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const norm = (s) => String(s || '').toLowerCase().normalize('NFD')
  .replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')

// The seven Māori electorates. Named explicitly rather than inferred: the
// general/Māori split is not derivable from a seat name, and getting it wrong
// would put a seat in the wrong roll.
const MAORI = new Set(['hauraki-waikato', 'ikaroa-rawhiti', 'tamaki-makaurau',
  'te-tai-hauauru', 'te-tai-tokerau', 'te-tai-tonga', 'waiariki'])

const rows = readFileSync('scripts/data/electorate-candidates-2026.csv', 'utf8')
  .trim().split(/\r?\n/).slice(1)
const seats = new Map()
for (const l of rows) {
  const m = l.match(/^(?:"((?:[^"]|"")*)"|([^,]*)),(.*),(.*)$/)
  if (!m) throw new Error(`unparsed CSV row: ${l}`)
  const name = m[3].trim()
  if (!seats.has(norm(name))) seats.set(norm(name), { name, slug: norm(name), n: 0 })
  seats.get(norm(name)).n++
}

// Seats in the 2023 dataset that are NOT contested in 2026.
const prev = new Set()
for (const line of readFileSync('src/constants/electorates-data.ts', 'utf8').split('\n')) {
  const m = line.match(/name:\s*'([^']+)'/)
  if (m) prev.add(norm(m[1]))
}
const gone = [...prev].filter((s) => !seats.has(s))
const fresh = [...seats.keys()].filter((s) => !prev.has(s))

const general = [...seats.values()].filter((s) => !MAORI.has(s.slug))
const maori = [...seats.values()].filter((s) => MAORI.has(s.slug))
if (seats.size !== 71 || general.length !== 64 || maori.length !== 7) {
  throw new Error(`expected 71 seats (64 general + 7 Māori), got ${seats.size} (${general.length} + ${maori.length})`)
}

const row = (s) => `  { name: ${`'${s.name.replace(/'/g, "\'")}',`.padEnd(27)} slug: ${`'${s.slug}',`.padEnd(24)} type: '${MAORI.has(s.slug) ? 'maori' : 'general'}',${fresh.includes(s.slug) ? ' newIn2026: true,' : ''} candidates: ${s.n} },`
const byName = (a, b) => a.name.localeCompare(b.name, 'en')

const out = `/**
 * The 71 electorates contested at the 2026 General Election.
 *
 * WHY THIS FILE EXISTS SEPARATELY FROM electorates-data.ts. Those are two
 * different things, and conflating them put 43 people who are not standing on
 * the live site while 138 real candidates were missing.
 *   - electorates-data.ts  = the 72 seats of the 2023 election, who holds each
 *     one now, and the Stats NZ "General & Māori Electorates 2020" geometry the
 *     map draws. It is about the CURRENT Parliament and is still correct for that.
 *   - this file            = what people are actually voting for on 7 Nov 2026.
 *
 * The Representation Commission released the final 2026 boundaries and names on
 * 8 August 2025. The lower North Island fell below population quota, so the
 * country went from 72 seats to 71: ${general.length} general and ${maori.length} Māori.
 *
 * GENERATED by scripts/gen-electorates-2026.mjs from the Electoral Commission's
 * official candidate list (scripts/data/electorate-candidates-2026.csv,
 * published 9 October 2026, nominations closed). Do not hand-edit: every seat
 * here is one the Commission actually accepted nominations for, which is why a
 * typo cannot creep in. The generator asserts the ${seats.size}/${general.length}/${maori.length} split and throws
 * if the CSV stops agreeing with it.
 *
 * \`candidates\` is the official count per seat, kept as a check: if the ingest
 * produces a different number for a seat, one of the two is wrong.
 */

export interface Electorate2026 {
  name: string
  slug: string
  type: 'general' | 'maori'
  /** Created in the 2025 boundary review — so it has NO sitting MP, and the
   *  battleground page must not render a defender for it. */
  newIn2026?: boolean
  /** Official candidate count from the Electoral Commission's list. */
  candidates: number
}

export const ELECTORATES_2026: Electorate2026[] = [
${general.sort(byName).map(row).join('\n')}
  // ── Māori electorates ───────────────────────────────────────────────────
${maori.sort(byName).map(row).join('\n')}
]

export const ELECTORATE_2026_SLUGS = ELECTORATES_2026.map((e) => e.slug)

const BY_SLUG = new Map(ELECTORATES_2026.map((e) => [e.slug, e]))
export const get2026Electorate = (slug: string): Electorate2026 | undefined =>
  BY_SLUG.get(slug)
export const isContested2026 = (slug: string): boolean => BY_SLUG.has(slug)

/**
 * Seats that existed in 2023 but are NOT contested in 2026.
 *
 * Kept so the site can say what happened rather than 404 on a URL someone
 * bookmarked or a search engine indexed. Deliberately NOT mapped to a
 * "successor": most of these were split across more than one new seat, and
 * naming a single heir would invent a continuity the Commission did not create
 * — which would then show the wrong MP as a seat's defender.
 */
export const SUPERSEDED_2023 = [
${gone.sort().map((s) => `  '${s}',`).join('\n')}
] as const
`
writeFileSync('src/constants/electorates-2026.ts', out, 'utf8')
console.log(`wrote src/constants/electorates-2026.ts`)
console.log(`  ${seats.size} seats (${general.length} general, ${maori.length} Māori)`)
console.log(`  new in 2026 (${fresh.length}): ${fresh.join(', ')}`)
console.log(`  superseded (${gone.length}): ${gone.join(', ')}`)
